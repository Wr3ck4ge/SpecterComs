    #[test]
    fn sps_detection() {
        assert!(has_sps_annexb(&[0, 0, 0, 1, 0x67, 0x64, 0, 0x33]));
        assert!(has_sps_annexb(&[0, 0, 1, 0x27, 0x64]));
        assert!(!has_sps_annexb(&[0, 0, 0, 1, 0x65, 0x88]));
    }
