// ── Annex-B / SPS helpers ─────────────────────────────────────────────────────

/// Returns `true` if `data` (Annex-B) contains at least one SPS NAL unit (type 7).
/// Used to decide whether we need to prepend SPS+PPS from the encoder extradata.
#[cfg(target_os = "windows")]
fn has_sps_annexb(data: &[u8]) -> bool {
    let len = data.len();
    let mut i = 0;
    while i + 3 <= len {
        let sc4 = i + 4 <= len
            && data[i] == 0 && data[i+1] == 0 && data[i+2] == 0 && data[i+3] == 1;
        let sc3 = !sc4
            && data[i] == 0 && data[i+1] == 0 && data[i+2] == 1;
        if sc4 {
            if i + 5 <= len && (data[i+4] & 0x1F) == 7 { return true; }
            i += 4;
        } else if sc3 {
            if i + 4 <= len && (data[i+3] & 0x1F) == 7 { return true; }
            i += 3;
        } else {
            i += 1;
        }
    }
    false
}

/// Converts an AVCDecoderConfigurationRecord (AVCC extradata from AVCodecContext.extradata)
/// into Annex-B SPS+PPS bytes suitable for prepending to a keyframe packet.
#[cfg(target_os = "windows")]
fn avcc_extradata_to_annexb(avcc: &[u8]) -> Vec<u8> {
    if avcc.len() < 7 { return Vec::new(); }
    let mut out = Vec::new();
    let num_sps = (avcc[5] & 0x1F) as usize;
    let mut i = 6;
    for _ in 0..num_sps {
        if i + 2 > avcc.len() { return out; }
        let n = u16::from_be_bytes([avcc[i], avcc[i+1]]) as usize;
        i += 2;
        if i + n > avcc.len() { return out; }
        out.extend_from_slice(&[0, 0, 0, 1]);
        out.extend_from_slice(&avcc[i..i+n]);
        i += n;
    }
    if i >= avcc.len() { return out; }
    let num_pps = avcc[i] as usize;
    i += 1;
    for _ in 0..num_pps {
        if i + 2 > avcc.len() { return out; }
        let n = u16::from_be_bytes([avcc[i], avcc[i+1]]) as usize;
        i += 2;
        if i + n > avcc.len() { return out; }
        out.extend_from_slice(&[0, 0, 0, 1]);
        out.extend_from_slice(&avcc[i..i+n]);
        i += n;
    }
    out
}

/// AMF quality preset for an encode load: "quality" up to ~1080p30 of
/// pixels per second (+15 % slack so 1920×1080 ultrawide-budget sizes like
/// 2714×762 qualify), "balanced" above. Pure, unit-tested.
fn amf_quality_preset(enc_w: u32, enc_h: u32, fps: u32) -> &'static str {
    const QUALITY_MAX_PX_PER_S: u64 = 1920 * 1080 * 30 * 115 / 100;
    if enc_w as u64 * enc_h as u64 * fps.max(1) as u64 <= QUALITY_MAX_PX_PER_S { "quality" } else { "balanced" }
}

/// True if `name` is an option of the codec context or its private (codec)
/// options — i.e. a dictionary key avcodec_open2 would actually consume.
#[cfg(target_os = "windows")]
unsafe fn opt_exists(ctx: *mut ffi::AVCodecContext, name: &str) -> bool {
    let Ok(c) = std::ffi::CString::new(name) else { return false };
    !ffi::av_opt_find(ctx as *mut std::ffi::c_void, c.as_ptr(), std::ptr::null(), 0, ffi::AV_OPT_SEARCH_CHILDREN as i32).is_null()
}

/// The value FFmpeg holds for an option (searching the private options too).
#[cfg(target_os = "windows")]
unsafe fn opt_get(ctx: *mut ffi::AVCodecContext, name: &str) -> Option<String> {
    let c = std::ffi::CString::new(name).ok()?;
    let mut out: *mut u8 = std::ptr::null_mut();
    let r = ffi::av_opt_get(ctx as *mut std::ffi::c_void, c.as_ptr(), ffi::AV_OPT_SEARCH_CHILDREN as i32, &mut out);
    if r < 0 || out.is_null() { return None; }
    let s = std::ffi::CStr::from_ptr(out as *const std::os::raw::c_char).to_string_lossy().into_owned();
    ffi::av_free(out as *mut std::ffi::c_void);
    Some(s)
}

// ── Capture diagnostic logger ───────────────────────────────────────────────────
// Writes to stderr AND appends to %TEMP%\specter_capture_debug.txt so diagnostics
// are visible both when running from a terminal and as a persistent file the user
// can share after a test session.
#[cfg(target_os = "windows")]
fn capture_log(msg: &str) {
    eprintln!("{msg}");
    use std::io::Write;
    let path = std::env::temp_dir().join("specter_capture_debug.txt");
    if let Ok(mut f) = std::fs::OpenOptions::new().create(true).append(true).open(path) {
        let _ = writeln!(f, "{msg}");
    }
}

